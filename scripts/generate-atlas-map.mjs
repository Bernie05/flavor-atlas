// Generates src/features/atlas/landPath.ts: the atlas map's coastlines as one SVG path.
// Run it only when BOUNDS change (e.g. a cuisine from outside East Asia). Its map
// libraries stay out of the app's dependencies, so install them in a temp folder:
//
//   mkdir /tmp/atlas-map && cd /tmp/atlas-map && npm init -y
//   npm i world-atlas@2 topojson-client@3 topojson-simplify@3 d3-geo@3
//   cp <repo>/scripts/generate-atlas-map.mjs . && node generate-atlas-map.mjs <repo>/src/features/atlas/landPath.ts
//
// Keep the projection math in sync with projectPoint() in src/features/atlas/utils.ts.
import fs from 'node:fs'
import { geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'
import { presimplify, simplify } from 'topojson-simplify'

const land50 = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'))
// Planar simplification in square degrees: keeps coastlines recognizable at phone size.
const MIN_WEIGHT = Number(process.env.MIN_WEIGHT ?? 0.01)
const simplified = simplify(presimplify(land50), MIN_WEIGHT)
const land = feature(simplified, simplified.objects.land)

// The part of the world the atlas covers: northern Japan to Mindanao, Sichuan to the Pacific.
const BOUNDS = { west: 100, east: 147, south: 4, north: 47 }
const WIDTH = 360

const rad = (deg) => (deg * Math.PI) / 180
const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + rad(lat) / 2))

// The same formulas as projectPoint() in src/features/atlas/utils.ts.
const scale = WIDTH / rad(BOUNDS.east - BOUNDS.west)
const tx = -scale * rad(BOUNDS.west)
const ty = scale * mercY(BOUNDS.north)
const HEIGHT = Math.round(ty - scale * mercY(BOUNDS.south))

const projection = geoMercator().scale(scale).translate([tx, ty]).clipExtent([[0, 0], [WIDTH, HEIGHT]])
const raw = geoPath(projection).digits(1)(land)

// Drop specks smaller than a pixel or two: they cost bytes and nobody sees them.
const subpaths = raw.split(/(?=M)/).filter((part) => {
  const nums = part.match(/-?\d+(\.\d+)?/g)?.map(Number) ?? []
  const xs = nums.filter((_, i) => i % 2 === 0)
  const ys = nums.filter((_, i) => i % 2 === 1)
  return Math.max(...xs) - Math.min(...xs) > 2 || Math.max(...ys) - Math.min(...ys) > 2
})
const path = subpaths.join('')

const out = `// Generated by scripts/generate-atlas-map.mjs from Natural Earth 1:50m land (public domain), via the world-atlas
// package (ISC), projected with Mercator and clipped to BOUNDS. Do not edit by hand:
// the generator lives outside the app so its map libraries never enter the bundle.

/** The part of the world the atlas covers, in degrees. */
export const BOUNDS = ${JSON.stringify(BOUNDS)} as const

/** The map's coordinate space (SVG viewBox), in map units. */
export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}

/** Every coastline in BOUNDS as one SVG path. */
export const LAND_PATH =
  '${path}'
`
fs.writeFileSync(process.argv[2], out)
console.log({ WIDTH, HEIGHT, scale: scale.toFixed(2), subpaths: subpaths.length, dropped: raw.split(/(?=M)/).length - subpaths.length, bytes: out.length })
